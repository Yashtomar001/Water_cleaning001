/*
# Phytoplankton Bloom Prediction System - India Lakes

## Overview
Creates the full schema for an ML-based phytoplankton bloom prediction system
covering Indian freshwater lakes and rivers. This is a single-tenant (no auth) app:
all data is intentionally public/shared for environmental monitoring and early warning.

## New Tables

### `lakes`
Master registry of Indian lakes/rivers monitored by the system.
- id (uuid, PK)
- name (text) - lake/river name
- type (text) - 'lake' | 'river' | 'reservoir' | 'wetland'
- state (text) - Indian state
- district (text) - district
- lat (numeric) - latitude
- lng (numeric) - longitude
- area_sqkm (numeric) - surface area in sq km
- max_depth_m (numeric) - max depth in meters
- status (text) - 'safe' | 'watch' | 'warning' | 'critical'
- last_bloom_date (date) - most recent bloom event
- created_at (timestamptz)

### `monitoring_data`
Time-series environmental readings from sensors/satellites per lake.
- id (uuid, PK)
- lake_id (uuid FK -> lakes)
- recorded_at (timestamptz)
- temperature_c (numeric) - water temperature
- ph (numeric) - pH level
- dissolved_oxygen_mgl (numeric) - DO in mg/L
- turbidity_ntu (numeric) - turbidity
- chlorophyll_a_ugl (numeric) - chlorophyll-a concentration (bloom indicator)
- nitrate_mgl (numeric) - nitrogen
- phosphate_mgl (numeric) - phosphorus
- rainfall_mm (numeric) - recent rainfall
- sunlight_hours (numeric) - daily sunlight

### `predictions`
ML model bloom probability predictions per lake.
- id (uuid, PK)
- lake_id (uuid FK -> lakes)
- predicted_at (timestamptz)
- bloom_probability (numeric 0-1)
- predicted_intensity (text) - 'none' | 'low' | 'moderate' | 'high' | 'severe'
- risk_level (text) - 'low' | 'moderate' | 'high' | 'critical'
- contributing_factors (jsonb) - key factor breakdown
- model_version (text)

### `alerts`
Early warning alerts generated by the system.
- id (uuid, PK)
- lake_id (uuid FK -> lakes)
- alert_type (text) - 'bloom_warning' | 'water_quality' | 'threshold_exceeded'
- severity (text) - 'info' | 'warning' | 'critical'
- message (text)
- created_at (timestamptz)
- is_active (boolean, default true)
- acknowledged (boolean, default false)

## Security
- RLS enabled on all tables.
- Grants to anon + authenticated (no-auth single-tenant app, data intentionally public).
- All policies use USING (true) / WITH CHECK (true) because this is shared public
  environmental monitoring data with no per-user ownership.
*/

-- ============================================================
-- LAKES
-- ============================================================
CREATE TABLE IF NOT EXISTS lakes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  type text NOT NULL DEFAULT 'lake',
  state text NOT NULL,
  district text NOT NULL DEFAULT '',
  lat numeric NOT NULL,
  lng numeric NOT NULL,
  area_sqkm numeric,
  max_depth_m numeric,
  status text NOT NULL DEFAULT 'safe',
  last_bloom_date date,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE lakes ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON lakes TO anon, authenticated;

DROP POLICY IF EXISTS "anon_select_lakes" ON lakes;
CREATE POLICY "anon_select_lakes" ON lakes FOR SELECT
  TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "anon_insert_lakes" ON lakes;
CREATE POLICY "anon_insert_lakes" ON lakes FOR INSERT
  TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "anon_update_lakes" ON lakes;
CREATE POLICY "anon_update_lakes" ON lakes FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "anon_delete_lakes" ON lakes;
CREATE POLICY "anon_delete_lakes" ON lakes FOR DELETE
  TO anon, authenticated USING (true);

-- ============================================================
-- MONITORING_DATA
-- ============================================================
